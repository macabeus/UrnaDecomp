"""Generate probe-main.c: a main() that CALLS each root function once with dummy arguments, so the wasm-opt
inlining decisions of the probe link mirror an application that calls those functions (an exported function is
"used globally" and is never inlined-and-removed; a called one with other internal callers has refs > 1 like in the app).
usage: gen-probe-main.py <roots.txt> <objdump-x of the archive/objects, one or more files> <out.c>
Signatures come from `wasm-objdump -x` of the objects (Type section + Function section names). Roots whose
signature is not found are reported and skipped.
"""
import re, sys
roots = [l.strip() for l in open(sys.argv[1]) if l.strip() and not l.startswith('#')]
out = sys.argv[-1]
sigs = {}
for path in sys.argv[2:-1]:
    types = {}
    cur = None
    for line in open(path, errors='replace'):
        if line.startswith('Type['): cur = 'type'; continue
        if line.startswith('Function['): cur = 'func'; continue
        if re.match(r'^[A-Z][A-Za-z]+\[', line) or line.startswith('Code') or line.startswith('Custom'): cur = None if not line.startswith(('Type[','Function[')) else cur
        if cur == 'type':
            m = re.match(r'\s*- type\[(\d+)\] \((.*?)\) -> (.*)$', line)
            if m:
                params = [p for p in m.group(2).split(', ') if p]
                res = m.group(3).strip()
                results = [] if res == 'nil' else [r for r in res.split(', ') if r]
                types[int(m.group(1))] = (params, results)
        elif cur == 'func':
            m = re.match(r'\s*- func\[\d+\] sig=(\d+) <(.+)>$', line)
            if m and m.group(2) not in sigs and int(m.group(1)) in types:
                sigs[m.group(2)] = types[int(m.group(1))]
ctype = {'i32': 'int', 'i64': 'long long', 'f32': 'float', 'f64': 'double'}
lines = ['/* generated by tools/libs/openssl/gen-probe-main.py: calls each root once */', '#ifdef __cplusplus', 'extern "C" {', '#endif', 'volatile int sink;', 'volatile long long sink64; volatile double sinkd;']
calls = []; missing = []
for r in roots:
    if r not in sigs: missing.append(r); continue
    params, results = sigs[r]
    decl = f"{ctype[results[0]] if results else 'void'} {r}({', '.join(ctype[p] for p in params) or 'void'});"
    args = ', '.join(('(int)sink' if p == 'i32' else '(long long)sink64' if p == 'i64' else '(float)sinkd' if p == 'f32' else 'sinkd') for p in params)
    call = f"{r}({args});"
    if results:
        call = (f"sink = (int){r}({args});" if results[0] == 'i32' else f"sink64 = (long long){r}({args});" if results[0] == 'i64' else f"sinkd = {r}({args});")
    lines.append(decl); calls.append(call)
lines += ['#ifdef __cplusplus', '}', '#endif']
lines.append('int main(void) {')
lines.append('  if (sink == 0) return 0;')  # never taken at run time, but every call is a real call site
lines += ['  ' + c for c in calls]
lines.append('  return 0;\n}')
open(out, 'w').write('\n'.join(lines) + '\n')
print(f'{len(calls)} roots called, {len(missing)} without signature: {" ".join(missing[:20])}')
