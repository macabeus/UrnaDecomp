"""Generate the roots TU that keeps a candidate TU's functions alive in a whole-skeleton link.

usage: gen_try_roots.py <out.cpp> [--keep-weak] <object.o>...   (run on the host; needs wasm-objdump and docker-build.sh)

Nothing in the skeleton calls a candidate TU, so wasm-ld would drop its functions (--gc-sections) and whatever survived,
wasm-opt would remove as unreachable. The generated TU takes the ADDRESS of every strong function symbol of the objects
(`T` in llvm-nm; `--keep-weak` adds the `W` inline/template instantiations) and stores it into a volatile sink from a
static constructor: the functions become table entries, reachable from __wasm_call_ctors, with their bodies intact
(binaryen neither inlines-and-removes nor changes the signature of an address-taken function). An address-taken function
is not an export, so the export set stays the target's. Each function is declared through an asm label with its
WASM-level signature (from `wasm-objdump -x` of the object: i32 → int, i64 → long long, f32 → float, f64 → double), so
wasm-ld sees no signature mismatch.
"""
import re
import subprocess
import sys

CTYPE = {'i32': 'int', 'i64': 'long long', 'f32': 'float', 'f64': 'double'}
HERE = __file__.rsplit('/tools/round/', 1)[0]


def objdump_sigs(obj):
    """symbol -> (params, results) for every function the object defines."""
    out = subprocess.run(['wasm-objdump', '-x', obj], capture_output=True, text=True, check=True).stdout
    types, sigs, section = {}, {}, None
    for line in out.splitlines():
        if re.match(r'^[A-Z][A-Za-z]*\[', line) or line.startswith(('Code', 'Custom')):
            section = 'type' if line.startswith('Type[') else 'func' if line.startswith('Function[') else None
            continue
        if section == 'type':
            m = re.match(r'\s*- type\[(\d+)\] \((.*?)\) -> (.*)$', line)
            if m:
                params = [p for p in m.group(2).split(', ') if p]
                res = m.group(3).strip()
                types[int(m.group(1))] = (params, [] if res == 'nil' else res.split(', '))
        elif section == 'func':
            m = re.match(r'\s*- func\[\d+\] sig=(\d+) <(.+)>$', line)
            if m:
                sigs[m.group(2)] = types[int(m.group(1))]
    return sigs


def defined_functions(obj, keep_weak):
    out = subprocess.run(
        ['bash', f'{HERE}/build/docker-build.sh', '/emsdk/upstream/bin/llvm-nm', '-g', '--defined-only', obj],
        capture_output=True, text=True, check=True, cwd=HERE,
    ).stdout
    kinds = 'TW' if keep_weak else 'T'
    return [l.split()[-1] for l in out.splitlines() if len(l.split()) >= 2 and l.split()[-2] in kinds]


def main():
    args = sys.argv[1:]
    keep_weak = '--keep-weak' in args
    exclude = [a.split('=',1)[1] for a in args if a.startswith('--exclude=')]
    args = [a for a in args if a != '--keep-weak' and not a.startswith('--exclude=')]
    out, objs = args[0], args[1:]
    decls, stores, skipped = [], [], []
    n = 0
    for obj in objs:
        sigs = objdump_sigs(obj)
        for sym in defined_functions(obj, keep_weak):
            if sym == 'main' or sym not in sigs or any(x in sym for x in exclude):
                skipped.append(sym)
                continue
            params, results = sigs[sym]
            ret = CTYPE[results[0]] if results else 'void'
            if len(results) > 1:
                skipped.append(sym)
                continue
            decls.append(f'{ret} urna_try_{n}({", ".join(CTYPE[p] for p in params)}) __asm__("{sym}");  // {sym}')
            stores.append(f'  urna_try_sink = (void*)&urna_try_{n};')
            n += 1
    with open(out, 'w') as f:
        f.write('// generated by tools/round/gen_try_roots.py: address-takes every function of the candidate TU(s)\n')
        f.write('// so the whole-skeleton link keeps them (see the script header for why a call site is not needed).\n')
        f.write('extern "C" {\n' + '\n'.join(decls) + '\n}\n')
        f.write('static void* volatile urna_try_sink;\n')
        f.write('__attribute__((constructor)) static void urna_try_keep() {\n' + '\n'.join(stores) + '\n}\n')
    print(f'{n} functions rooted → {out}' + (f'; skipped {len(skipped)}: {" ".join(skipped[:10])}' if skipped else ''))


if __name__ == '__main__':
    main()
