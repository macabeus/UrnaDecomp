"""Write src/web/wasm_shim.cpp: the app's 32 EM_JS functions, bodies from src/web/library_vota.pretty.js
(the glue's EM_JS text, prettier-formatted), C signatures from the target's import types.
usage: python3 -I tools/extract/gen_wasm_shim.py <target.wasm> <ledger/import-names.json> <library_vota.pretty.js> <out.cpp>
The wasm import type decides the C type of every parameter and the return (i32 -> int, f64 -> double,
nil -> void); the parameter NAMES come from the JS function header, because emcc copies them from the
EM_JS parameter list into the glue (`function js_init(width,height){...}`). The body is kept as prettier
wrote it: emcc re-minifies EM_JS bodies with acorn, so only the token stream has to agree with the target.
"""
import json, re, subprocess, sys

wasm, names_json, pretty, out = sys.argv[1:5]
names = json.load(open(names_json))
objdump = subprocess.run(['wasm-objdump', '-x', wasm], capture_output=True, text=True, check=True).stdout
types = {}
sigs = {}
for line in objdump.splitlines():
    m = re.match(r'\s*- type\[(\d+)\] \((.*?)\) -> (.*)$', line)
    if m:
        params = [p for p in m.group(2).split(', ') if p]
        res = m.group(3).strip()
        types[int(m.group(1))] = (params, [] if res == 'nil' else res.split(', '))
    m = re.match(r'\s*- func\[\d+\] sig=(\d+) <a\.(\S+)> <- a\.', line)
    if m:
        sigs[names[m.group(2)]] = types[int(m.group(1))]
ctype = {'i32': 'int', 'i64': 'long long', 'f32': 'float', 'f64': 'double'}

funcs = []  # (name, [param names], body lines) in glue order
cur = None
for line in open(pretty, encoding='utf-8'):
    m = re.match(r'^function (\w+)\((.*)\) \{$', line)
    if m and cur is None:
        cur = (m.group(1), [p.strip() for p in m.group(2).split(',') if p.strip()], [])
        continue
    if line.rstrip('\n') == '}' and cur is not None:
        funcs.append(cur); cur = None; continue
    if cur is not None:
        cur[2].append(line.rstrip('\n'))
assert cur is None

lines = ['// The vota app\'s JavaScript side: 34 EM_JS functions (web console tags CWasmScreen, CWasmThread,',
         '// CWasmResource, CWasmSound, CWasmBeep). Generated by tools/extract/gen_wasm_shim.py from src/web/library_vota.pretty.js',
         '// (the EM_JS text emcc put in the target glue) and the target\'s import types; edit the generator, not this file.',
         '// emcc minifies every body with acorn, so what must agree with the target is the token stream, the parameter',
         '// names and the order of the functions (the glue lists EM_JS functions in link order of the em_js sections).',
         '#include <emscripten/em_js.h>', '']
for name, params, body in funcs:
    ptypes, results = sigs[name]
    assert len(ptypes) == len(params), (name, ptypes, params)
    ret = ctype[results[0]] if results else 'void'
    plist = ', '.join(f'{ctype[t]} {p}' for t, p in zip(ptypes, params))
    lines.append(f'EM_JS({ret}, {name}, ({plist}), {{')
    lines.extend(body)
    lines.append('});')
    lines.append('')
open(out, 'w', encoding='utf-8').write('\n'.join(lines))
print(f'{len(funcs)} EM_JS functions -> {out}')
